#!/usr/bin/env python3
"""Build the single-file Colab notebooks from the Jupytext sources.

The Colab bundles used to be hand-edited copies that drifted from
`notebooks/`. Now they are generated: `lab22/*.py` is written with
`%%writefile`, then every notebook's cells follow in order.

    python scripts/build_colab.py          # rewrite colab/*.ipynb
    python scripts/build_colab.py --check  # exit 1 if they are stale
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
WORKDIR = "/content/lab22"
STAGES = [
    ("00_dpo_loss_from_scratch", "core · CPU"),
    ("01_sft_mini", "core"),
    ("02_preference_data", "core"),
    ("03_dpo_train", "core"),
    ("04_compare_and_eval", "core"),
    ("03b_dpo_variants", "bonus"),
    ("05_merge_deploy_gguf", "bonus"),
    ("06_benchmark", "bonus"),
    ("07_grpo_bonus", "bonus"),
]
TARGETS = {"T4": "Lab22_DPO_T4.ipynb", "BIGGPU": "Lab22_DPO_BigGPU.ipynb"}
BONUS_FLAGS = {
    "03b_dpo_variants": "variants",
    "05_merge_deploy_gguf": "gguf",
    "06_benchmark": "benchmark",
    "07_grpo_bonus": "grpo",
}
CELL = re.compile(r"^# %%(?P<md> \[markdown\])?.*$", re.MULTILINE)


def requirements() -> list[str]:
    """Requirement specs from requirements.txt, minus test/notebook tooling."""
    skip = ("jupyterlab", "jupytext", "pytest", "llama-cpp-python", "lm-eval")
    specs = []
    for line in (REPO / "requirements.txt").read_text(encoding="utf-8").splitlines():
        spec = line.split("#", 1)[0].strip()
        if spec and not spec.startswith(skip):
            specs.append(spec)
    return specs


def source_lines(text: str) -> list[str]:
    lines = text.splitlines(keepends=True)
    if lines:
        lines[-1] = lines[-1].rstrip("\n")
    return lines


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": source_lines(text)}


def code(text: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": source_lines(text)}


def percent_cells(path: Path) -> list[dict]:
    """Parse a Jupytext py:percent file (header block dropped)."""
    text = path.read_text(encoding="utf-8")
    marks = list(CELL.finditer(text))
    cells = []
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(text)
        body = text[m.end() :end].strip("\n")
        if not body.strip():
            continue
        if m.group("md"):
            body = "\n".join(line[2:] if line.startswith("# ") else line.lstrip("#") for line in body.splitlines())
            cells.append(md(body))
        else:
            cells.append(code(body))
    return cells


RELEASE_GPU = (
    "# Free GPU memory held by the previous stage (model, trainer, llama.cpp handle).\n"
    "import gc\n"
    "for _name in ('trainer', 'model', 'ref_model', 'llm', 'policy', 'ref', 'tokenizer'):\n"
    "    globals().pop(_name, None)\n"
    "gc.collect()\n"
    "try:\n"
    "    import torch\n"
    "    if torch.cuda.is_available():\n"
    "        torch.cuda.empty_cache()\n"
    "        print(f'GPU memory in use: {torch.cuda.memory_allocated() / 1e9:.2f} GB')\n"
    "except ImportError:\n"
    "    pass"
)


def render(tier: str) -> dict:
    big = tier == "BIGGPU"
    pins = repr(requirements())
    cells = [
        md(
            f"# Lab 22 — DPO/ORPO Alignment ({'BigGPU' if big else 'T4'} tier)\n\n"
            "**Track 3 · Day 22 · VinUni AICB.** Generated by `scripts/build_colab.py` from "
            "`notebooks/*.py` and `lab22/*.py`; do not edit by hand.\n\n"
            "**Đã điền hàm loss và giải thích NB0.** Chọn GPU rồi chạy từ trên xuống. "
            "Mặc định chỉ chạy NB0 → NB4; bonus phải bật trong cell cấu hình.\n\n"
            "Sau NB4 có kiểm tra và tải ZIP kết quả. Lưu notebook đã chạy bằng "
            "**Tệp → Tải xuống → .ipynb** để giữ output. Điền REFLECTION bằng số liệu thật.\n\n"
            "Nếu mất phiên, file trong `/content` sẽ mất. Có thể bật lưu Google Drive "
            "ở cell cấu hình. Nếu chỉ khởi động lại kernel và file còn trên đĩa, "
            "chạy lại phần A rồi tiếp tục từ notebook bị lỗi. "
            "Thay đổi tier/tham số sau khi đã import `lab22` thì cần khởi động lại kernel."
        ),
        md("## A. Setup"),
        code(
            "import os\n"
            f'os.environ["COMPUTE_TIER"] = "{tier}"\n'
            "SAVE_TO_DRIVE = False  # True: lưu model và kết quả qua các phiên Colab\n"
            "RUN_BONUS = dict(variants=False, gguf=False, benchmark=False, grpo=False)\n"
            '# os.environ["MAX_LEN"] = "512"  # giảm nếu GPU hết bộ nhớ\n'
            "# NB4 judges automatically with a panel of two local reward models (no key needed).\n"
            "# Optional API judge as a cross-check (two A/B orders):\n"
            '# os.environ["JUDGE_PROVIDER"] = "gemini"   # or "openai" / "anthropic"\n'
            '# os.environ["JUDGE_MODEL"] = "<current model id>"\n'
            '# from google.colab import userdata; os.environ["GEMINI_API_KEY"] = userdata.get("GEMINI_API_KEY")\n'
            "# Put API keys in Colab secrets, never in the notebook."
        ),
        code(
            "import subprocess\nimport sys\n"
            f"packages = {pins}\n"
            "if RUN_BONUS['gguf']:\n"
            "    packages.append('llama-cpp-python>=0.3.16,<1.0')\n"
            "if RUN_BONUS['benchmark']:\n"
            "    packages.append('lm-eval[ifeval,math]>=0.4.13,<0.5')\n"
            + ("if RUN_BONUS['grpo']:\n    packages.append('vllm>=0.10')\n" if big else "")
            + "subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', *packages], check=True)\n"
            "# Unsloth cần được import trước torch/transformers/trl.\n"
            "import unsloth\nimport torch\n"
            "assert torch.cuda.is_available(), 'Chọn Runtime → Change runtime type → GPU rồi chạy lại.'\n"
            "gpu = torch.cuda.get_device_properties(0)\n"
            "print(f'GPU: {gpu.name} · {gpu.total_memory / 1e9:.1f} GB')"
        ),
        code(
            "from pathlib import Path\n"
            "if SAVE_TO_DRIVE:\n"
            "    from google.colab import drive\n"
            "    drive.mount('/content/drive')\n"
            "    WORK = Path('/content/drive/MyDrive/Lab22')\n"
            "else:\n"
            f'    WORK = Path("{WORKDIR}")\n'
            '(WORK / "lab22").mkdir(parents=True, exist_ok=True)\n'
            "os.chdir(WORK)\n"
            "print(Path.cwd())"
        ),
        md("### Helper package `lab22/` (same files as the repo)"),
    ]
    for module in sorted((REPO / "lab22").glob("*.py")):
        body = module.read_text(encoding="utf-8")
        cells.append(code(f"%%writefile lab22/{module.name}\n{body}"))
    # Keep verification and submission instructions available without cloning the repo.
    cells.append(code("(WORK / 'scripts').mkdir(exist_ok=True)\n(WORK / 'notebooks').mkdir(exist_ok=True)\n"
                      "(WORK / 'submission' / 'screenshots').mkdir(parents=True, exist_ok=True)"))
    for relative in ["scripts/verify.py", "submission/REFLECTION.md", "submission/screenshots/README.md"]:
        template = "scripts/templates/REFLECTION.md" if relative == "submission/REFLECTION.md" else relative
        body = (REPO / template).read_text(encoding="utf-8")
        # Do not replace an existing reflection when rerunning setup.
        cells.append(code(f"_path = WORK / {relative!r}\n"
                          f"if not _path.exists():\n    _path.write_text({body!r}, encoding='utf-8')"))
    for stem, _ in STAGES:
        body = (REPO / "notebooks" / f"{stem}.py").read_text(encoding="utf-8")
        cells.append(code(f"%%writefile notebooks/{stem}.py\n{body}"))
    for i, (stem, kind) in enumerate(STAGES):
        if i:
            # One Colab kernel runs every stage, so drop the previous stage's GPU objects.
            cells.append(code(RELEASE_GPU))
        cells.append(md(f"---\n# ⏵ `notebooks/{stem}.py` ({kind})"))
        stage_cells = percent_cells(REPO / "notebooks" / f"{stem}.py")
        if stem in BONUS_FLAGS:
            flag = BONUS_FLAGS[stem]
            cells.append(code(f"print('Chạy bonus {flag}' if RUN_BONUS[{flag!r}] else 'Bỏ qua bonus {flag}')"))
            for cell in stage_cells:
                if cell["cell_type"] == "code":
                    body = "".join(cell["source"])
                    cell["source"] = source_lines(f"if RUN_BONUS[{flag!r}]:\n" + textwrap.indent(body, "    "))
        cells.extend(stage_cells)
        if stem == "04_compare_and_eval":
            cells.extend(submission_cells())
    # nbformat 4.5 requires a unique id on every cell.
    for index, cell in enumerate(cells):
        cell["id"] = f"lab22-{tier.lower()}-{index:04d}"
    return {
        "cells": cells,
        "metadata": {
            "accelerator": "GPU",
            "colab": {"gpuType": "A100" if big else "T4", "provenance": []},
            "kernelspec": {"display_name": "Python 3", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def submission_cells() -> list[dict]:
    return [
        md("## B. Lưu kết quả phần bắt buộc\n\n"
           "Kiểm tra bên dưới có thể báo REFLECTION chưa điền; đó là phần bạn viết sau khi xem số liệu. "
           "Mở `submission/REFLECTION.md` trong bảng Files và điền mục 1–4, 6 "
           "(mục 3 ≥100 từ, mục 6 ≥150 từ). Chạy lại cell kiểm tra và tải ZIP sau khi điền.\n\n"
           "ZIP chứa bằng chứng nhỏ, mã nguồn và bài phản tư. Trọng số model không nằm trong ZIP. "
           "Tải riêng notebook đang mở dưới dạng `.ipynb` để giữ output; Colab không tự ghi output vào ZIP. "
           "Nếu chạy bonus, chạy lại cell ZIP sau khi bonus hoàn tất."),
        code("import subprocess\nimport sys\n"
             "verification = subprocess.run([sys.executable, 'scripts/verify.py'], "
             "capture_output=True, text=True)\n"
             "print(verification.stdout)\n"
             "if verification.stderr:\n    print(verification.stderr)\n"
             "print('Đủ bằng chứng theo verify.' if verification.returncode == 0 "
             "else 'Còn mục cần hoàn thiện ở danh sách trên.')"),
        code("from zipfile import ZipFile, ZIP_DEFLATED\n"
             "archive = WORK.parent / 'Lab22_submission.zip'\n"
             "allowed = {'.py', '.md', '.json', '.jsonl', '.parquet', '.png', '.jpg', '.jpeg'}\n"
             "with ZipFile(archive, 'w', compression=ZIP_DEFLATED) as bundle:\n"
             "    folders = ('lab22', 'scripts', 'notebooks', 'submission', 'data/pref', 'data/eval', 'adapters')\n"
             "    for folder in folders:\n"
             "        for path in sorted((WORK / folder).rglob('*')):\n"
             "            if path.is_file() and path.suffix.lower() in allowed and '__pycache__' not in path.parts:\n"
             "                bundle.write(path, path.relative_to(WORK))\n"
             "print(f'Đã lưu {archive} ({archive.stat().st_size / 1e6:.1f} MB)')\n"
             "from google.colab import files\nfiles.download(str(archive))"),
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if colab/*.ipynb differ from the sources")
    args = parser.parse_args()
    stale = []
    for tier, name in TARGETS.items():
        path = REPO / "colab" / name
        nb = render(tier)
        if args.check:
            if not path.exists() or json.loads(path.read_text(encoding="utf-8")) != nb:
                stale.append(name)
            continue
        path.write_text(json.dumps(nb, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"wrote colab/{name} ({len(nb['cells'])} cells)")
    if stale:
        print(f"stale: {stale}; run `python scripts/build_colab.py`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
